  const parts = [{"file":"survival-v118.pck.part00","bytes":94371840,"sha256":"d3c898a1f61558435fc1a06cd405bfcb8c89332191777775f3e117127d4849ac"},{"file":"survival-v118.pck.part01","bytes":85353132,"sha256":"836ea985d845ce31956fa1f32a23d306c3429cffe6fd769782fa72bac4c06409"}];
